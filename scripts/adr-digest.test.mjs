/** The stable prefix of the derived line — the handle every assertion grabs. */
const MARKER = 'Next free project ADR number:';

/** Contract §3: the substring the band guard must print on stderr. */
const BAND_MESSAGE = 'outside the project ADR band 0001-0999';

/** Written into every band-guard run's --out target; must survive a loud failure. */
const SENTINEL = 'SENTINEL — a run that fails the band guard must not write this file.\n';

// ---------------------------------------------------------------------------
// Process helper — spawnSync so an exit code is data, not a throw. A spawn
// FAILURE (ENOENT, EMFILE) is folded into stderr so it can never be misread as
// a content failure.
// ---------------------------------------------------------------------------
function runDigest(args) {
  const result = spawnSync('node', [SCRIPT, ...args], {
    cwd: ROOT,
    encoding: 'utf8',
    stdio: 'pipe',
  });
  const spawnError = result.error ? `\n[spawn error] ${result.error.message}` : '';
  return {
    code: result.status !== null ? result.status : 1,
    stderr: `${result.stderr ?? ''}${spawnError}`,
    stdout: result.stdout ?? '',
  };
}

// ---------------------------------------------------------------------------
// Fixture builder — canonical header shape, copied from
// evals/fixtures/adr-digest/0900-good.md and checked against validateAdr():
// Status, Date, Slice, Supersedes, Amends, Subsystems, Decision are all
// required (LEGACY_TOLERANCE is empty), and main() exits 1 BEFORE
// generateDigest() when any is missing. A bare stub would make this whole
// suite unfalsifiable — it would fail for the wrong reason.
// ---------------------------------------------------------------------------
function adrDoc(fields) {
  const lines = [
    `# ADR-${fields.id} — ${fields.title}`,
    '',
    `**Status:** ${fields.status}`,
    `**Date:** ${fields.date}`,
    `**Slice:** ${fields.slice}`,
    '**Supersedes:** —',
    '**Amends:** —',
    `**Subsystems:** ${fields.subsystems}`,
    `**Decision:** ${fields.decision}`,
  ];
  // Status: Superseded additionally needs a REAL in-directory Superseded-by
  // target, or validateAdr() in scripts/adr-digest.mjs raises its "Status is
  // Superseded but missing a real ... pointer" error and we never reach
  // generation. (Cited by declaration, not by line: that check sat in the low
  // 260s on 2026-09-07 and is expected to drift.)
  if (typeof fields.supersededBy === 'string') {
    lines.push(`**Superseded-by:** ${fields.supersededBy}`);
  }
  // rb-70 passthroughs. Both are OMITTED unless asked for — that default IS the
  // "the fields are optional" fixture, and it is what keeps X1-X4 byte-identical.
  // Position within the preamble is irrelevant to both readers (the bold-field
  // reader indexes the preamble; the back-link reader scans preamble lines), so
  // appending here rather than beside **Amends:** costs nothing.
  if (typeof fields.extends === 'string') {
    lines.push(`**Extends:** ${fields.extends}`);
  }
  if (typeof fields.extendedBy === 'string') {
    lines.push(`**Extended-by:** ${fields.extendedBy}`);
  }
  // Raw lines appended to the END of the preamble (X7/G4 plants a fenced or an
  // indented relation line here) and to the END of the body (X7/G4 plants a
  // column-0 relation line BELOW the first `## ` heading there).
  for (const raw of fields.extraPreamble ?? []) lines.push(raw);
  lines.push('', '## Context', '', 'Synthetic fixture written by scripts/adr-digest.test.mjs.', '');
  for (const raw of fields.extraBody ?? []) lines.push(raw);
  return lines.join('\n');
}

/**
 * Declare one fixture ADR. `file` defaults to the canonical NNNN-slug.md shape;
 * X4 overrides it to plant an out-of-band filename whose slice(0,4) id is still
 * collected by collectAdrIds' /^[0-9]{4}.*\.md$/ filter.
 */
function adr(id, options = {}) {
  const fields = {
    id,
    title: options.title ?? `Synthetic fixture ${id}`,
    status: options.status ?? 'Accepted',
    date: options.date ?? '2026-07-13',
    slice: options.slice ?? 'rb-43',
    subsystems: options.subsystems ?? 'tooling-docs',
    decision: options.decision ?? `Synthetic decision text for fixture ${id}; short and valid.`,
    supersededBy: options.supersededBy,
    extends: options.extends,
    extendedBy: options.extendedBy,
    extraPreamble: options.extraPreamble,
    extraBody: options.extraBody,
  };
  return { file: options.file ?? `${id}-synthetic-fixture.md`, content: adrDoc(fields) };
}

/** Materialise a corpus in a fresh mkdtemp dir and hand it to `fn`. */
function withCorpus(entries, fn) {
  const dir = mkdtempSync(join(tmpdir(), 'adr-digest-corpus-'));
  try {
    for (const entry of entries) {
      writeFileSync(join(dir, entry.file), entry.content, 'utf8');
    }
    return fn(dir);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** Generate into a throwaway out dir; return the run plus the generated bytes. */
function generateFrom(adrDir) {
  const outDir = mkdtempSync(join(tmpdir(), 'adr-digest-out-'));
  try {
    const out = join(outDir, 'DIGEST.md');
    const run = runDigest(['--adr-dir', adrDir, '--out', out]);
    return { ...run, content: existsSync(out) ? readFileSync(out, 'utf8') : '' };
  } finally {
    rmSync(outDir, { recursive: true, force: true });
  }
}

// ---------------------------------------------------------------------------
// Expected-line construction and extraction (String methods only)
// ---------------------------------------------------------------------------

/** The one true template. `highestId === null` renders the empty-corpus form. */
function expectedNextFreeLine(nextId, highestId) {
  const opening =
    highestId === null
      ? `${MARKER} **\`${nextId}\`** — no project ADRs on disk.`
      : `${MARKER} **\`${nextId}\`** — the highest id on disk (\`${highestId}\`) plus one. ` +
        'Gaps below it are never reused (`0002`–`0034` belong to the harness spec corpus).';
  return (
    `${opening} Regenerated by \`just adr-digest\` and drift-gated by \`just ci\`; it is a ` +
    'measurement, not a reservation — when a number is reserved for an in-flight slice the ' +
    'supervisor ledger is ahead of this line and is authoritative.'
  );
}

/** The trimmed marker line, or null when the generator renders none. */
function nextFreeLine(content) {
  for (const line of content.split('\n')) {
    if (line.trim().startsWith(MARKER)) return line.trim();
  }
  return null;
}

/**
 * The id inside the BOLD-CODE token, anchored on `**\`` … `\`**` rather than on
 * the first backtick pair: a future reword that adds an earlier inline-code
 * token would otherwise make X5 silently compare something else.
 */
function nextFreeIdFrom(line) {
  if (line === null) return null;
  const open = line.indexOf('**`');
  if (open === -1) return null;
  const close = line.indexOf('`**', open + 3);
  if (close === -1) return null;
  return line.slice(open + 3, close);
}

function countOccurrences(haystack, needle) {
  let count = 0;
  let idx = haystack.indexOf(needle);
  while (idx !== -1) {
    count++;
    idx = haystack.indexOf(needle, idx + needle.length);
  }
  return count;
}

// ---------------------------------------------------------------------------
// X6's LOCAL predicates. All three are positive-controlled inside X6 before
// they are pointed at the real README, so a red there is a finding and not a
// broken matcher.
// ---------------------------------------------------------------------------
function splitParagraphs(text) {
  const paragraphs = [];
  let current = [];
  for (const line of text.split('\n')) {
    if (line.trim() === '') {
      if (current.length > 0) {
        paragraphs.push(current.join('\n'));
        current = [];
      }
    } else {
      current.push(line);
    }
  }
  if (current.length > 0) paragraphs.push(current.join('\n'));
  return paragraphs;
}

/**
 * Fold every spelling of the phrase together: lowercase, then collapse runs of
 * whitespace, underscores and hyphens to one space. This is what makes
 * `next-free`, `next_free`, `.adr_next_free` and an ordinary hard wrap
 * (`the next\nfree number`) all match the single needle `next free` — a
 * three-spelling includes() test was measured to miss the wrapped shape.
 */
function normalizeForPhrase(text) {
  return text.toLowerCase().replace(/[\s_-]+/g, ' ');
}

function mentionsNextFree(paragraph) {
  return normalizeForPhrase(paragraph).includes('next free');
}

/** Paragraphs that both mention a next-free number AND carry a 4-digit run. */
function staleNextFreeParagraphs(text) {
  const violations = [];
  for (const paragraph of splitParagraphs(text)) {
    if (!mentionsNextFree(paragraph)) continue;
    if (/[0-9]{4}/.test(paragraph)) violations.push(paragraph);
  }
  return violations;
}

/**
 * Paragraphs that mention next-free AND name DIGEST.md — the "moved, not
 * deleted" predicate. Deleting the clause outright satisfies the stale-digit
 * check vacuously and would leave ADR-0060's "see docs/adr/README.md for the
 * current next-free number" pointing at nothing.
 */
function nextFreeParagraphsNamingDigest(text) {
  return splitParagraphs(text).filter((p) => mentionsNextFree(p) && p.includes('DIGEST.md'));
}

/**
 * Phrase-INDEPENDENT census: four-digit runs >= 0100 that survive stripping the
 * legitimate citation forms (an `ADR-NNNN` reference, a `(./NNNN-...)` link
 * target, a `[NNNN]` link label, a bare `NNNN-slug.md` path). A reworded
 * "Start your new ADR at **`0236`**" carries no next-free phrase at all and is
 * invisible to the two paragraph predicates; this one still sees the digit.
 * The >= 0100 floor is what lets README keep citing the harness block and the
 * collision note.
 *
 * A plausible YEAR (19xx/20xx) is not an ADR-number claim and is excluded:
 * "last restructured in 2026 by slice rb-43" is an innocent README edit, and
 * reporting it would red `just test` under a message about a hand-maintained
 * ADR number that is not there. Project ids stop at 0999, so no real next-free
 * number can hide behind this exclusion. Everything else stays as-is — this is
 * the leg that kills the "Next available number: **`0236`**" reword cheat.
 */
function loudDigitsOutsideCitations(text) {
  const stripped = text
    .replace(/\(\.\/[0-9]{4}[^)]*\)/g, ' ')
    .replace(/\[[0-9]{4}[\]]/g, ' ')
    .replace(/ADR-[0-9]{4}/g, ' ')
    .replace(/[0-9]{4}-[a-z0-9-]*\.md/g, ' ');
  const found = new Set();
  for (const match of stripped.matchAll(/[0-9]{4}/g)) {
    const token = match[0];
    if (/^(19|20)[0-9]{2}$/.test(token)) continue;
    if (Number(token) >= 100) found.add(token);
  }
  return [...found].sort();
}

