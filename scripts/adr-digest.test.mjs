// ===========================================================================
// X3 — reachability: the line is computed from the corpus AND lives inside the
// payload `--check` compares. FOUR and-ed legs, all measured before asserting.
//
// KILLS: (a) a constant line that does not move when the corpus grows;
// (c) a line spliced in at writeFileSync time — such an implementation makes a
// digest look stale against its own corpus; (d) the survivor of (c): a splice
// at write PLUS a matching strip of the line from `committed` before the
// compare, which passes legs (a)-(c) and is only caught by FORGING the value
// in the committed file and demanding that --check notices. Leg (b) alone
// proves nothing: today, with no feature at all, a bigger corpus already
// drifts on the table rows.
// ===========================================================================
test('X3 the derived line moves with the corpus and round-trips through --check', () => {
  const corpusA = [
    adr('0140', { subsystems: 'tooling-docs' }),
    adr('0205', { subsystems: 'ci-gates' }),
  ];
  const corpusB = [...corpusA, adr('0310', { subsystems: 'battle, content' })];

  const outDir = mkdtempSync(join(tmpdir(), 'adr-digest-x3-'));
  try {
    const digestA = join(outDir, 'DIGEST-A.md');

    const generateA = withCorpus(corpusA, (dirA) => {
      const run = runDigest(['--adr-dir', dirA, '--out', digestA]);
      return { code: run.code, stderr: run.stderr };
    });
    assert.equal(
      generateA.code,
      0,
      `X3: corpus A generation should exit 0. stderr: ${generateA.stderr.slice(0, 400)}`,
    );

    const lineA = nextFreeLine(readFileSync(digestA, 'utf8'));
    const lineB = withCorpus(corpusB, (dirB) => nextFreeLine(generateFrom(dirB).content));

    // Leg (b): A's digest is stale for corpus B.
    const checkB = withCorpus(corpusB, (dirB) =>
      runDigest(['--check', '--adr-dir', dirB, '--out', digestA]),
    );

    // Leg (c): A's digest is fresh for corpus A — the splice-at-write killer.
    const checkA = withCorpus(corpusA, (dirA) =>
      runDigest(['--check', '--adr-dir', dirA, '--out', digestA]),
    );

    // Leg (d): forge ONLY the id inside the bold-code token of the committed
    // digest and re-check. This asserts payload membership directly instead of
    // inferring it from a clean round-trip.
    const committed = readFileSync(digestA, 'utf8');
    const open = committed.indexOf('**`');
    const close = open === -1 ? -1 : committed.indexOf('`**', open + 3);
    let forgedCheck = 'not-attempted (no bold-code token in the generated digest)';
    if (open !== -1 && close !== -1) {
      writeFileSync(
        digestA,
        `${committed.slice(0, open + 3)}0184${committed.slice(close)}`,
        'utf8',
      );
      const run = withCorpus(corpusA, (dirA) =>
        runDigest(['--check', '--adr-dir', dirA, '--out', digestA]),
      );
      forgedCheck = run.code === 0 ? 'zero' : 'non-zero';
    }

    assert.deepEqual(
      {
        lineA,
        lineB,
        linesDiffer: lineA !== lineB,
        checkStaleCorpus: checkB.code === 0 ? 'zero' : 'non-zero',
        checkOwnCorpus: checkA.code === 0 ? 'zero' : 'non-zero',
        checkForgedNumber: forgedCheck,
      },
      {
        lineA: expectedNextFreeLine('0206', '0205'),
        lineB: expectedNextFreeLine('0311', '0310'),
        linesDiffer: true,
        checkStaleCorpus: 'non-zero',
        checkOwnCorpus: 'zero',
        checkForgedNumber: 'non-zero',
      },
      'X3: checkOwnCorpus must be zero (a splice at write time makes a digest stale against ' +
        'its own corpus) AND checkForgedNumber must be non-zero (a splice plus a matching ' +
        `strip before the compare passes every other leg). stderr(own): ${checkA.stderr.slice(0, 300)}`,
    );
  } finally {
    rmSync(outDir, { recursive: true, force: true });
  }
});

