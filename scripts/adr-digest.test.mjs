// ===========================================================================
// X2 — exact line, exact position, and sole ownership of the number.
//
// KILLS five measured cheats that all satisfy a bare `content.includes(...)`:
// (a) rendering inside an HTML comment (`<!-- Next free ... -->`) — the trim()
// EQUALITY rejects the `<!--` prefix; (b) rendering at end-of-file — the
// position assertions reject it; (c) INDENTING the line by four spaces, which
// markdown renders as a code block and which a trim()-only comparison accepts
// — the raw column-0 equality rejects it; (d) opening an unbalanced `<!--`
// earlier in the header region so the whole block (line included) is invisible
// while every structural assertion still holds — the balanced-comment count
// rejects it; (e) leaving a SECOND, contradictory hand-maintained number
// elsewhere in the digest — the sole-bold-code-token count rejects it. The
// bold-code shape `**\`` occurs nowhere else in a generated digest: the ADR
// table, the H- table and both notes use neither bold nor code there.
// ===========================================================================
test('X2 renders the line exactly once, verbatim, right after the Generated from line', () => {
  const entries = [
    adr('0120', { subsystems: 'tooling-docs' }),
    adr('0130', { subsystems: 'ci-gates, tooling-docs' }),
  ];
  withCorpus(entries, (dir) => {
    const run = generateFrom(dir);
    assert.equal(run.code, 0, `X2: generation should exit 0 but exited ${run.code}. ${run.stderr}`);

    const expected = expectedNextFreeLine('0131', '0130');
    const lines = run.content.split('\n');

    assert.equal(
      countOccurrences(run.content, MARKER),
      1,
      'X2: the next-free marker must appear EXACTLY ONCE in the generated digest',
    );

    const exactMatches = lines.filter((line) => line.trim() === expected).length;
    assert.equal(
      exactMatches,
      1,
      'X2: exactly one line must EQUAL the contract template verbatim (an HTML-comment ' +
        'wrapper or any reworded prose fails this equality while passing a substring test)',
    );

    const generatedIdx = lines.findIndex((line) => line.startsWith('Generated from '));
    assert.notEqual(generatedIdx, -1, 'X2: the digest must still carry the `Generated from ` line');

    let cursor = generatedIdx + 1;
    while (cursor < lines.length && lines[cursor].trim() === '') cursor++;
    assert.equal(
      lines[cursor] === undefined ? null : lines[cursor].trim(),
      expected,
      'X2: the next-free line must be the FIRST non-empty line after the `Generated from ` ' +
        'line (an end-of-file render passes a substring test and fails here)',
    );
    assert.equal(
      cursor,
      generatedIdx + 2,
      'X2: exactly one blank line must separate the `Generated from ` line from the next-free line',
    );

    // Leg: RAW equality at column 0 — a four-space indent renders as a code
    // block and is invisible as prose, but survives every trim()-based check.
    assert.equal(
      lines[cursor] === undefined ? null : lines[cursor],
      expected,
      'X2: the line must start at column 0 — an indented copy renders as a code block',
    );

    // Leg: the header region must not sit inside an unclosed HTML comment.
    const header = lines.slice(0, cursor + 1).join('\n');
    assert.equal(
      countOccurrences(header, '<!--'),
      countOccurrences(header, '-->'),
      'X2: HTML comment openers and closers must balance above the next-free line — an ' +
        'unbalanced `<!--` hides the whole header region from a reader while every ' +
        'structural assertion above still holds',
    );

    // Leg: exactly one bold-code number in the whole generated digest.
    assert.equal(
      countOccurrences(run.content, '**`'),
      1,
      'X2: the digest must carry exactly ONE bold-code number — a second, contradictory ' +
        'hand-maintained one elsewhere in the file is the bug this slice exists to remove',
    );
  });
});

// ===========================================================================
// X3 — reachability: the line is computed from the corpus AND lives inside the
// payload `--check` compares. FOUR and-ed legs, all measured before asserting.
//
// KILLS: (a) a constant line that does not move when the corpus grows;
// (c) a line spliced in at writeFileSync time — such an implementation makes a
// digest look stale against its own corpus; (d) the survivor of (c): a splice
// at write PLUS a matching strip of the line from `committed` before the
// compare, which passes legs (a)-(c) and is only caught by FORGING the value
// in the committed file and demanding that --check notices. Leg (b) alone
// proves nothing: today, with no feature at all, a bigger corpus already
// drifts on the table rows.
// ===========================================================================
test('X3 the derived line moves with the corpus and round-trips through --check', () => {
  const corpusA = [
    adr('0140', { subsystems: 'tooling-docs' }),
    adr('0205', { subsystems: 'ci-gates' }),
  ];
  const corpusB = [...corpusA, adr('0310', { subsystems: 'battle, content' })];

  const outDir = mkdtempSync(join(tmpdir(), 'adr-digest-x3-'));
  try {
    const digestA = join(outDir, 'DIGEST-A.md');

    const generateA = withCorpus(corpusA, (dirA) => {
      const run = runDigest(['--adr-dir', dirA, '--out', digestA]);
      return { code: run.code, stderr: run.stderr };
    });
    assert.equal(
      generateA.code,
      0,
      `X3: corpus A generation should exit 0. stderr: ${generateA.stderr.slice(0, 400)}`,
    );

    const lineA = nextFreeLine(readFileSync(digestA, 'utf8'));
    const lineB = withCorpus(corpusB, (dirB) => nextFreeLine(generateFrom(dirB).content));

    // Leg (b): A's digest is stale for corpus B.
    const checkB = withCorpus(corpusB, (dirB) =>
      runDigest(['--check', '--adr-dir', dirB, '--out', digestA]),
    );

    // Leg (c): A's digest is fresh for corpus A — the splice-at-write killer.
    const checkA = withCorpus(corpusA, (dirA) =>
      runDigest(['--check', '--adr-dir', dirA, '--out', digestA]),
    );

    // Leg (d): forge ONLY the id inside the bold-code token of the committed
    // digest and re-check. This asserts payload membership directly instead of
    // inferring it from a clean round-trip.
    const committed = readFileSync(digestA, 'utf8');
    const open = committed.indexOf('**`');
    const close = open === -1 ? -1 : committed.indexOf('`**', open + 3);
    let forgedCheck = 'not-attempted (no bold-code token in the generated digest)';
    if (open !== -1 && close !== -1) {
      writeFileSync(
        digestA,
        `${committed.slice(0, open + 3)}0184${committed.slice(close)}`,
        'utf8',
      );
      const run = withCorpus(corpusA, (dirA) =>
        runDigest(['--check', '--adr-dir', dirA, '--out', digestA]),
      );
      forgedCheck = run.code === 0 ? 'zero' : 'non-zero';
    }

    assert.deepEqual(
      {
        lineA,
        lineB,
        linesDiffer: lineA !== lineB,
        checkStaleCorpus: checkB.code === 0 ? 'zero' : 'non-zero',
        checkOwnCorpus: checkA.code === 0 ? 'zero' : 'non-zero',
        checkForgedNumber: forgedCheck,
      },
      {
        lineA: expectedNextFreeLine('0206', '0205'),
        lineB: expectedNextFreeLine('0311', '0310'),
        linesDiffer: true,
        checkStaleCorpus: 'non-zero',
        checkOwnCorpus: 'zero',
        checkForgedNumber: 'non-zero',
      },
      'X3: checkOwnCorpus must be zero (a splice at write time makes a digest stale against ' +
        'its own corpus) AND checkForgedNumber must be non-zero (a splice plus a matching ' +
        `strip before the compare passes every other leg). stderr(own): ${checkA.stderr.slice(0, 300)}`,
    );
  } finally {
    rmSync(outDir, { recursive: true, force: true });
  }
});

