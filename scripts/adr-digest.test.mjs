/** The one true template. `highestId === null` renders the empty-corpus form. */
function expectedNextFreeLine(nextId, highestId) {
  const opening =
    highestId === null
      ? `${MARKER} **\`${nextId}\`** — no project ADRs on disk.`
      : `${MARKER} **\`${nextId}\`** — the highest id on disk (\`${highestId}\`) plus one. ` +
        'Gaps below it are never reused (`0002`–`0034` belong to the harness spec corpus).';
  return (
    `${opening} Regenerated by \`just adr-digest\` and drift-gated by \`just ci\`; it is a ` +
    'measurement, not a reservation — when a number is reserved for an in-flight slice the ' +
    'supervisor ledger is ahead of this line and is authoritative.'
  );
}

/** The trimmed marker line, or null when the generator renders none. */
function nextFreeLine(content) {
  for (const line of content.split('\n')) {
    if (line.trim().startsWith(MARKER)) return line.trim();
  }
  return null;
}

/**
 * The id inside the BOLD-CODE token, anchored on `**\`` … `\`**` rather than on
 * the first backtick pair: a future reword that adds an earlier inline-code
 * token would otherwise make X5 silently compare something else.
 */
function nextFreeIdFrom(line) {
  if (line === null) return null;
  const open = line.indexOf('**`');
  if (open === -1) return null;
  const close = line.indexOf('`**', open + 3);
  if (close === -1) return null;
  return line.slice(open + 3, close);
}

function countOccurrences(haystack, needle) {
  let count = 0;
  let idx = haystack.indexOf(needle);
  while (idx !== -1) {
    count++;
    idx = haystack.indexOf(needle, idx + needle.length);
  }
  return count;
}

// ---------------------------------------------------------------------------
// X6's LOCAL predicates. All three are positive-controlled inside X6 before
// they are pointed at the real README, so a red there is a finding and not a
// broken matcher.
// ---------------------------------------------------------------------------
function splitParagraphs(text) {
  const paragraphs = [];
  let current = [];
  for (const line of text.split('\n')) {
    if (line.trim() === '') {
      if (current.length > 0) {
        paragraphs.push(current.join('\n'));
        current = [];
      }
    } else {
      current.push(line);
    }
  }
  if (current.length > 0) paragraphs.push(current.join('\n'));
  return paragraphs;
}

/**
 * Fold every spelling of the phrase together: lowercase, then collapse runs of
 * whitespace, underscores and hyphens to one space. This is what makes
 * `next-free`, `next_free`, `.adr_next_free` and an ordinary hard wrap
 * (`the next\nfree number`) all match the single needle `next free` — a
 * three-spelling includes() test was measured to miss the wrapped shape.
 */
function normalizeForPhrase(text) {
  return text.toLowerCase().replace(/[\s_-]+/g, ' ');
}

function mentionsNextFree(paragraph) {
  return normalizeForPhrase(paragraph).includes('next free');
}

/** Paragraphs that both mention a next-free number AND carry a 4-digit run. */
function staleNextFreeParagraphs(text) {
  const violations = [];
  for (const paragraph of splitParagraphs(text)) {
    if (!mentionsNextFree(paragraph)) continue;
    if (/[0-9]{4}/.test(paragraph)) violations.push(paragraph);
  }
  return violations;
}

/**
 * Paragraphs that mention next-free AND name DIGEST.md — the "moved, not
 * deleted" predicate. Deleting the clause outright satisfies the stale-digit
 * check vacuously and would leave ADR-0060's "see docs/adr/README.md for the
 * current next-free number" pointing at nothing.
 */
function nextFreeParagraphsNamingDigest(text) {
  return splitParagraphs(text).filter((p) => mentionsNextFree(p) && p.includes('DIGEST.md'));
}

/**
 * Phrase-INDEPENDENT census: four-digit runs >= 0100 that survive stripping the
 * legitimate citation forms (an `ADR-NNNN` reference, a `(./NNNN-...)` link
 * target, a `[NNNN]` link label, a bare `NNNN-slug.md` path). A reworded
 * "Start your new ADR at **`0236`**" carries no next-free phrase at all and is
 * invisible to the two paragraph predicates; this one still sees the digit.
 * The >= 0100 floor is what lets README keep citing the harness block and the
 * collision note.
 *
 * A plausible YEAR (19xx/20xx) is not an ADR-number claim and is excluded:
 * "last restructured in 2026 by slice rb-43" is an innocent README edit, and
 * reporting it would red `just test` under a message about a hand-maintained
 * ADR number that is not there. Project ids stop at 0999, so no real next-free
 * number can hide behind this exclusion. Everything else stays as-is — this is
 * the leg that kills the "Next available number: **`0236`**" reword cheat.
 */
function loudDigitsOutsideCitations(text) {
  const stripped = text
    .replace(/\(\.\/[0-9]{4}[^)]*\)/g, ' ')
    .replace(/\[[0-9]{4}[\]]/g, ' ')
    .replace(/ADR-[0-9]{4}/g, ' ')
    .replace(/[0-9]{4}-[a-z0-9-]*\.md/g, ' ');
  const found = new Set();
  for (const match of stripped.matchAll(/[0-9]{4}/g)) {
    const token = match[0];
    if (/^(19|20)[0-9]{2}$/.test(token)) continue;
    if (Number(token) >= 100) found.add(token);
  }
  return [...found].sort();
}

