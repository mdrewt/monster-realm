// ---------------------------------------------------------------------------
// Process helper — spawnSync so an exit code is data, not a throw. A spawn
// FAILURE (ENOENT, EMFILE) is folded into stderr so it can never be misread as
// a content failure.
// ---------------------------------------------------------------------------
function runDigest(args) {
  const result = spawnSync('node', [SCRIPT, ...args], {
    cwd: ROOT,
    encoding: 'utf8',
    stdio: 'pipe',
  });
  const spawnError = result.error ? `\n[spawn error] ${result.error.message}` : '';
  return {
    code: result.status !== null ? result.status : 1,
    stderr: `${result.stderr ?? ''}${spawnError}`,
    stdout: result.stdout ?? '',
  };
}

// ---------------------------------------------------------------------------
// Fixture builder — canonical header shape, copied from
// evals/fixtures/adr-digest/0900-good.md and checked against validateAdr():
// Status, Date, Slice, Supersedes, Amends, Subsystems, Decision are all
// required (LEGACY_TOLERANCE is empty), and main() exits 1 BEFORE
// generateDigest() when any is missing. A bare stub would make this whole
// suite unfalsifiable — it would fail for the wrong reason.
// ---------------------------------------------------------------------------
function adrDoc(fields) {
  const lines = [
    `# ADR-${fields.id} — ${fields.title}`,
    '',
    `**Status:** ${fields.status}`,
    `**Date:** ${fields.date}`,
    `**Slice:** ${fields.slice}`,
    '**Supersedes:** —',
    '**Amends:** —',
    `**Subsystems:** ${fields.subsystems}`,
    `**Decision:** ${fields.decision}`,
  ];
  // Status: Superseded additionally needs a REAL in-directory Superseded-by
  // target, or validateAdr() in scripts/adr-digest.mjs raises its "Status is
  // Superseded but missing a real ... pointer" error and we never reach
  // generation. (Cited by declaration, not by line: that check sat in the low
  // 260s on 2026-09-07 and is expected to drift.)
  if (typeof fields.supersededBy === 'string') {
    lines.push(`**Superseded-by:** ${fields.supersededBy}`);
  }
  // rb-70 passthroughs. Both are OMITTED unless asked for — that default IS the
  // "the fields are optional" fixture, and it is what keeps X1-X4 byte-identical.
  // Position within the preamble is irrelevant to both readers (the bold-field
  // reader indexes the preamble; the back-link reader scans preamble lines), so
  // appending here rather than beside **Amends:** costs nothing.
  if (typeof fields.extends === 'string') {
    lines.push(`**Extends:** ${fields.extends}`);
  }
  if (typeof fields.extendedBy === 'string') {
    lines.push(`**Extended-by:** ${fields.extendedBy}`);
  }
  // Raw lines appended to the END of the preamble (X7/G4 plants a fenced or an
  // indented relation line here) and to the END of the body (X7/G4 plants a
  // column-0 relation line BELOW the first `## ` heading there).
  for (const raw of fields.extraPreamble ?? []) lines.push(raw);
  lines.push('', '## Context', '', 'Synthetic fixture written by scripts/adr-digest.test.mjs.', '');
  for (const raw of fields.extraBody ?? []) lines.push(raw);
  return lines.join('\n');
}

/**
 * Declare one fixture ADR. `file` defaults to the canonical NNNN-slug.md shape;
 * X4 overrides it to plant an out-of-band filename whose slice(0,4) id is still
 * collected by collectAdrIds' /^[0-9]{4}.*\.md$/ filter.
 */
function adr(id, options = {}) {
  const fields = {
    id,
    title: options.title ?? `Synthetic fixture ${id}`,
    status: options.status ?? 'Accepted',
    date: options.date ?? '2026-07-13',
    slice: options.slice ?? 'rb-43',
    subsystems: options.subsystems ?? 'tooling-docs',
    decision: options.decision ?? `Synthetic decision text for fixture ${id}; short and valid.`,
    supersededBy: options.supersededBy,
    extends: options.extends,
    extendedBy: options.extendedBy,
    extraPreamble: options.extraPreamble,
    extraBody: options.extraBody,
  };
  return { file: options.file ?? `${id}-synthetic-fixture.md`, content: adrDoc(fields) };
}

/** Materialise a corpus in a fresh mkdtemp dir and hand it to `fn`. */
function withCorpus(entries, fn) {
  const dir = mkdtempSync(join(tmpdir(), 'adr-digest-corpus-'));
  try {
    for (const entry of entries) {
      writeFileSync(join(dir, entry.file), entry.content, 'utf8');
    }
    return fn(dir);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** Generate into a throwaway out dir; return the run plus the generated bytes. */
function generateFrom(adrDir) {
  const outDir = mkdtempSync(join(tmpdir(), 'adr-digest-out-'));
  try {
    const out = join(outDir, 'DIGEST.md');
    const run = runDigest(['--adr-dir', adrDir, '--out', out]);
    return { ...run, content: existsSync(out) ? readFileSync(out, 'utf8') : '' };
  } finally {
    rmSync(outDir, { recursive: true, force: true });
  }
}

