/// Cross-registry validation for encounter tables.
///
/// Checks:
/// - Unique zone ids
/// - `encounter_rate` in [0, 1000]
/// - Each entry has `weight > 0`
/// - Each entry has `min_level <= max_level`
/// - Each `species_id` exists in `species`
/// - Each `zone_id` exists in `zones`
///
/// # Errors
/// Returns `Err` with a descriptive message on the first violation found.
pub fn validate_encounters(
    tables: &[EncounterTable],
    species: &[Species],
    zones: &[ZoneDef],
) -> Result<(), String> {
    let species_ids: std::collections::BTreeSet<u32> = species.iter().map(|s| s.id).collect();
    let zone_ids: std::collections::BTreeSet<u32> = zones.iter().map(|z| z.id).collect();
    let mut seen_zones = std::collections::BTreeSet::new();

    for table in tables {
        if !seen_zones.insert(table.zone_id) {
            return Err(format!("duplicate encounter zone_id {}", table.zone_id));
        }
        if !zone_ids.contains(&table.zone_id) {
            return Err(format!(
                "encounter table references non-existent zone {}",
                table.zone_id
            ));
        }
        if table.encounter_rate > 1000 {
            return Err(format!(
                "encounter_rate {} for zone {} exceeds per-mille max 1000",
                table.encounter_rate, table.zone_id
            ));
        }
        // `encounter_rate == 0` is intentionally valid (a defined-but-never-
        // triggering "safe" zone): non-empty entries with rate 0 are allowed.
        // M8c's trigger rolls the rate first, so a 0-rate zone simply never fires.
        if table.entries.is_empty() {
            return Err(format!(
                "encounter table for zone {} has no entries",
                table.zone_id
            ));
        }
        let mut seen_species = std::collections::BTreeSet::new();
        for entry in &table.entries {
            if !seen_species.insert(entry.species_id) {
                return Err(format!(
                    "duplicate encounter species {} within zone {}",
                    entry.species_id, table.zone_id
                ));
            }
            if entry.weight == 0 {
                return Err(format!(
                    "encounter entry for species {} in zone {} has weight=0",
                    entry.species_id, table.zone_id
                ));
            }
            if entry.min_level.as_u8() > entry.max_level.as_u8() {
                return Err(format!(
                    "encounter entry for species {} in zone {} has inverted level range ({} > {})",
                    entry.species_id,
                    table.zone_id,
                    entry.min_level.as_u8(),
                    entry.max_level.as_u8()
                ));
            }
            if !species_ids.contains(&entry.species_id) {
                return Err(format!(
                    "encounter entry in zone {} references non-existent species {}",
                    table.zone_id, entry.species_id
                ));
            }
        }
    }
    Ok(())
}

/// Cross-registry content validation:
/// - Unique species ids, no zero base stats
/// - Every species must have at least one `learnable_skill_id` (non-empty moveset)
/// - Unique skill ids
/// - Unique type chart pairs (attacker, defender)
/// - Unique item ids
/// - All `learnable_skill_ids` in species must reference existing skills
///
/// # Errors
/// Returns `Err` with a descriptive message on the first integrity violation.
pub fn validate_content(
    species: &[Species],
    skills: &[SkillDef],
    type_chart: &[TypeRelation],
    items: &[ItemDef],
) -> Result<(), String> {
    let mut species_ids = std::collections::BTreeSet::new();
    for sp in species {
        if !species_ids.insert(sp.id) {
            return Err(format!("duplicate species id {}", sp.id));
        }
        let stats = [
            sp.base_stats.hp,
            sp.base_stats.attack,
            sp.base_stats.defense,
            sp.base_stats.speed,
            sp.base_stats.sp_attack,
            sp.base_stats.sp_defense,
        ];
        for &s in &stats {
            if s == 0 {
                return Err(format!("species {} has a zero base stat", sp.id));
            }
            if s > 255 {
                return Err(format!(
                    "species {} has base stat {} exceeding 255",
                    sp.id, s
                ));
            }
        }
    }

    let mut skill_ids = std::collections::BTreeSet::new();
    for sk in skills {
        if !skill_ids.insert(sk.id) {
            return Err(format!("duplicate skill id {}", sk.id));
        }
        if sk.power == 0 {
            return Err(format!(
                "skill {} has power=0; damaging skills must have power>0",
                sk.id
            ));
        }
        // accuracy_check is `roll < accuracy` with roll in 0..=99 (a percent chance).
        //   accuracy == 0  → always miss (no roll is < 0): an unusable skill.
        //   accuracy > 100 → outside the percent domain; every roll 0..=99 is < it,
        //                    identical in effect to 100, so reject it as malformed.
        // accuracy is a u8, so `> 100` covers 101..=255 with no overflow risk.
        if sk.accuracy == 0 || sk.accuracy > 100 {
            return Err(format!(
                "skill {} has accuracy {}; accuracy must be in [1, 100]",
                sk.id, sk.accuracy
            ));
        }
        // Weather cross-check (M14d, ADR-0095): exhaustive match with no wildcard
        // arm is the compile-time OCP gate — adding a new WeatherKind variant without
        // updating this site is a compile error (unlike `matches!` which has implicit `_`).
        if let Some(kind) = sk.sets_weather {
            match kind {
                WeatherKind::Rain
                | WeatherKind::Sun
                | WeatherKind::Sandstorm
                | WeatherKind::Hail => {}
            }
        }
        // Status cross-check (M14e, ADR-0096): same OCP gate for applies_status —
        // a new StatusKind variant without updating this site is a compile error.
        if let Some(kind) = sk.applies_status {
            use crate::combat::ability::StatusKind;
            match kind {
                StatusKind::Poison
                | StatusKind::Burn
                | StatusKind::Paralysis
                | StatusKind::Sleep
                | StatusKind::Freeze => {}
            }
        }
    }

    // Cross-check: every learnable_skill_id in species must exist in skills,
    // and every species must declare at least one learnable skill (an empty moveset
    // would cause pick_best_skill to panic at battle time — ADR-0049).
    for sp in species {
        if sp.learnable_skill_ids.is_empty() {
            return Err(format!(
                "species {} has no learnable_skill_ids; a species must have at least one learnable skill",
                sp.id
            ));
        }
        for &sid in &sp.learnable_skill_ids {
            if !skill_ids.contains(&sid) {
                return Err(format!(
                    "species {} references non-existent skill {}",
                    sp.id, sid
                ));
            }
        }
    }

    let mut type_pairs = std::collections::BTreeSet::new();
    for rel in type_chart {
        if !type_pairs.insert((rel.attacker, rel.defender)) {
            return Err(format!(
                "duplicate type chart pair ({:?}, {:?})",
                rel.attacker, rel.defender
            ));
        }
        if !matches!(rel.effectiveness, 0 | 5 | 10 | 20) {
            return Err(format!(
                "type chart pair ({:?}, {:?}) has illegal effectiveness {}; must be 0, 5, 10, or 20",
                rel.attacker, rel.defender, rel.effectiveness
            ));
        }
    }

    let mut item_ids = std::collections::BTreeSet::new();
    for item in items {
        if !item_ids.insert(item.id) {
            return Err(format!("duplicate item id {}", item.id));
        }
        // A bait bonus is per-mille; it can never exceed certainty (1000).
        if item.recruit_bonus > 1000 {
            return Err(format!(
                "item {} has recruit_bonus {} exceeding per-mille max 1000",
                item.id, item.recruit_bonus
            ));
        }
        // Training food (M9b-tail): a target stat needs a positive amount within the
        // per-stat EV cap; a non-training item must carry no stray train_amount.
        match item.train_stat {
            Some(_) => {
                if item.train_amount == 0 {
                    return Err(format!(
                        "item {} is a training food but train_amount is 0",
                        item.id
                    ));
                }
                if item.train_amount > EV_PER_STAT_CAP {
                    return Err(format!(
                        "item {} train_amount {} exceeds per-stat EV cap {EV_PER_STAT_CAP}",
                        item.id, item.train_amount
                    ));
                }
            }
            None => {
                if item.train_amount != 0 {
                    return Err(format!(
                        "item {} has train_amount {} but no train_stat (incoherent)",
                        item.id, item.train_amount
                    ));
                }
            }
        }
        // Single-role invariant (M14e, ADR-0096 RT-CV-01): an item that carries
        // both cure_status and train_stat is accepted by two independent reducers
        // (use_battle_item + train), making its consumption behaviour non-deterministic.
        if item.cure_status.is_some() && item.train_stat.is_some() {
            return Err(format!(
                "item {} has both cure_status and train_stat set; an item must have a single role",
                item.id
            ));
        }
    }

    Ok(())
}

/// Cross-registry content integrity for the essence-graph evolution model
/// (EG1-10, spec §5 rules R1-R12; ADR-0174 D6). The successor to the deleted
/// `validate_evolution_fusion`. Pure (errors-as-values, no clock/RNG); checks
/// run in a deterministic order so each proof-of-teeth fixture isolates exactly
/// one violation (ADR-0010).
///
/// - **R1** no duplicate `(from_species, to_species)` pair. NOTE (ADR-0174 D5):
///   this toolchain has no composite unique index, so this gate plus
///   `sync_content`'s duplicate-pair seed check are the ONLY enforcement — the
///   spec's "DB-level enforcement" claim is a named deviation.
/// - **R2** no self-evolution (`from_species != to_species`).
/// - **R3** no dangling species references (`from_species`/`to_species` must
///   exist). Essence affinities are an enum — dangling is unrepresentable — and
///   a path carries no item references, so species refs are the whole rule here.
/// - **R4** no vacuous path: reject when `min_level <= 1` AND `essence` is empty
///   AND all three history gates are `None`.
/// - **R5** tier monotonicity: `to.tier == from.tier + 1`, strict, no skipping.
/// - **R6** derived-forms-not-wild: no `to_species` may appear in an encounter table.
/// - **R7** `essence.len() <= 3` per path (panel legibility cap).
/// - **R8** fan-in is explicitly PERMITTED (two paths, same `to_species`,
///   different `from_species`, both validate) — a positive pin, not a check.
/// - **R9** `ItemDef.essence_affinity.is_some()` implies `train_stat` and
///   `cure_status` are both `None`.
/// - **R10** universal reachability: every `tier > 0` species is the
///   `to_species` of at least one path. **Carve-out (ADR-0174 D6):** R10 is
///   SKIPPED when `paths` is empty — EG1 ships explicit `tier: 1` species while
///   the edge set is empty until EG3, and without the skip `sync_content` could
///   never succeed and a fresh-DB `init` would panic for the whole window. An
///   empty graph is the declared pre-content state, not a shipped graph.
/// - **R11** tier cap: `Species.tier <= 5` (PROVISIONAL, spec §4).
/// - **R12** `edge_id` unique across the path set (cross-version append-only
///   enforcement is the eval gate's job, EG5-1).
///
/// # Errors
/// Returns `Err` with a descriptive message on the first integrity violation.
pub fn validate_evolution_paths(
    species: &[Species],
    paths: &[EvolutionPath],
    encounters: &[EncounterTable],
    items: &[ItemDef],
) -> Result<(), String> {
    // The rules run in DECLARED order R1 -> R12: the per-rule proof-of-teeth
    // fixtures (notably R2's `self` message, which a self-edge would otherwise
    // trip R5's tier arithmetic for) depend on it. Reordering is a spec change,
    // not a refactor.
    let tier_by_id: std::collections::HashMap<u32, u8> =
        species.iter().map(|sp| (sp.id, sp.tier)).collect();

    // R1: no duplicate (from_species, to_species) pair. The ONLY enforcement —
    // no composite unique index exists at the DB level (ADR-0174 D5) — and what
    // keeps evolve(monster_id, to_species) an unambiguous wire signature.
    let mut seen_pairs = std::collections::HashSet::new();
    for path in paths {
        if !seen_pairs.insert((path.from_species, path.to_species)) {
            return Err(format!(
                "R1: duplicate evolution pair {} -> {} (edge {})",
                path.from_species, path.to_species, path.edge_id
            ));
        }
    }

    // R2: no self-evolution.
    for path in paths {
        if path.from_species == path.to_species {
            return Err(format!(
                "R2: edge {} is a self-evolution: species {} evolves into itself",
                path.edge_id, path.from_species
            ));
        }
    }

    // R3: no dangling species reference, BOTH directions.
    for path in paths {
        if !tier_by_id.contains_key(&path.from_species) {
            return Err(format!(
                "R3: edge {} references missing from_species {}",
                path.edge_id, path.from_species
            ));
        }
        if !tier_by_id.contains_key(&path.to_species) {
            return Err(format!(
                "R3: edge {} references missing to_species {}",
                path.edge_id, path.to_species
            ));
        }
    }

    // R4: no vacuous path — a monster must not qualify at birth.
    for path in paths {
        if path.min_level.as_u8() <= 1
            && path.essence.is_empty()
            && path.min_trust_tier.is_none()
            && path.min_quality_time_tier.is_none()
            && path.min_nutrition_pct.is_none()
        {
            return Err(format!(
                "R4: edge {} is vacuous — min_level <= 1, no essence, and no history gates",
                path.edge_id
            ));
        }
    }

    // R5: tier monotonicity — every edge advances by exactly +1, no skipping.
    // R3 already guaranteed both lookups resolve.
    for path in paths {
        let from_tier = tier_by_id
            .get(&path.from_species)
            .copied()
            .ok_or_else(|| format!("R5: edge {} from_species vanished", path.edge_id))?;
        let to_tier = tier_by_id
            .get(&path.to_species)
            .copied()
            .ok_or_else(|| format!("R5: edge {} to_species vanished", path.edge_id))?;
        if u16::from(to_tier) != u16::from(from_tier) + 1 {
            return Err(format!(
                "R5: edge {} breaks tier monotonicity — species {} (tier {from_tier}) -> \
                 species {} (tier {to_tier}) must advance by exactly +1",
                path.edge_id, path.from_species, path.to_species
            ));
        }
    }

    // R6: derived forms are never wild-catchable.
    for path in paths {
        for table in encounters {
            if table
                .entries
                .iter()
                .any(|entry| entry.species_id == path.to_species)
            {
                return Err(format!(
                    "R6: evolution target species {} (edge {}) appears in the encounter table \
                     for zone {} — derived forms must not be wild-catchable",
                    path.to_species, path.edge_id, table.zone_id
                ));
            }
        }
    }

    // R7: essence legibility cap — at most 3 entries per path.
    for path in paths {
        if path.essence.len() > 3 {
            return Err(format!(
                "R7: edge {} carries {} essence requirements — the legibility cap is 3",
                path.edge_id,
                path.essence.len()
            ));
        }
    }

    // R8: fan-in (same to_species from different sources) is explicitly
    // PERMITTED — a positive pin, no check.

    // R9: an essence item is single-role — essence_affinity excludes both
    // train_stat and cure_status.
    for item in items {
        if item.essence_affinity.is_some()
            && (item.train_stat.is_some() || item.cure_status.is_some())
        {
            return Err(format!(
                "R9: item {} carries essence_affinity alongside train_stat/cure_status — \
                 an essence item must have no other consumption role",
                item.id
            ));
        }
    }

    // R10: universal reachability — every tier > 0 species is the to_species
    // of at least one edge. CARVE-OUT (ADR-0174 D6): SKIPPED ENTIRELY when the
    // path set is EMPTY — EG1 ships explicit `tier: 1` species while the edge
    // set stays empty until EG3, and without the skip `sync_content` could
    // never succeed and a fresh-DB `init` would panic for the whole window. An
    // empty graph is the declared pre-content state, not a shipped graph.
    if !paths.is_empty() {
        for sp in species {
            if sp.tier > 0 && !paths.iter().any(|path| path.to_species == sp.id) {
                return Err(format!(
                    "R10: species {} (tier {}) is unreachable — every tier > 0 species must be \
                     the to_species of at least one evolution path",
                    sp.id, sp.tier
                ));
            }
        }
    }

    // R11: tier cap (PROVISIONAL, spec §4).
    for sp in species {
        if sp.tier > 5 {
            return Err(format!(
                "R11: species {} has tier {} — above the cap of 5",
                sp.id, sp.tier
            ));
        }
    }

    // R12: edge_id is unique across the set (the durable edge identity, EG1-12).
    let mut seen_edge_ids = std::collections::HashSet::new();
    for path in paths {
        if !seen_edge_ids.insert(path.edge_id) {
            return Err(format!(
                "R12: edge_id {} is reused across evolution paths — edge_id is the durable, \
                 append-only edge identity",
                path.edge_id
            ));
        }
    }

    Ok(())
}

